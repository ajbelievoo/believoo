      (iv) Documents, as specified in Section 2, relating to beneficial owner, the managers, officers or employees, as the case may be, holding an attorney to transact on its behalf<br>
      (v) the names of the beneficiaries, trustees, settlor and authors of the trust<br>
      (vi) The address of the registered office of the trust; and list of trustees and documents, as are required for individuals under Section 2 for those discharging role as trustee and authorised to transact on behalf of the trust<br>
      (vii) Permanent Account Number or Form60 issued to the person holding POA on trust behalf<br>
      (viii) A declaration containing the names of all the beneficial owners together with their shareholding/controlling interest/stake duly signed by the authorized signatory. (Annexure III)<br>
      (ix) Copies of relevant extracts of trust deed dated obtained and perused, with special emphasis on the power of the trustees to sign cheques, delegation of authority, borrow money etc .The relevant portions are entered in the power of attorney register.<br>
      A copy of the resolution<br>
      (x) All Trust Accounts to be invariably assigned "High Risk"</td>

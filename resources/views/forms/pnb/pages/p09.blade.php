      <td>5</td><td><b>Hindu Undivided Family (HUF)</b></td>
      <td>Certified copies of each of the following documents shall be obtained:<br>
      (i) Joint Hindu Family letter dated ……………………………signed by all the adult coparceners.<br>
      (ii) Identification information as mentioned under Section 2 in respect of the Karta and Major Coparceners.<br>
      (iii) Declaration of HUF and its Karta.<br>
      (iv) Recent Passport photographs duly self-attested by major co-parceners alongwith their names and addresses.<br>
      (v) The Permanent Account Number or Form No.60 of the trust;<br>
      (vi) On death of a coparcener, birth of a coparcener and a minor coparcener attaining majority (18years),a fresh JHF letter has to be executed Declaration that a) the depositor is the Karta of the Joint Family b) the deposit belongs to JHF.</td>

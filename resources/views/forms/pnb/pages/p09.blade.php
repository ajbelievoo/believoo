      <td>2</td><td><b>Partnership Firms</b></td>
      <td>The certified copies of each of the following documents or the equivalent e-documents thereof shall be obtained:<br>
      (i) Registration certificate;<br>
      (ii) Partnership deed;<br>
      (iii) Permanent Account Number of the partnership firm;<br>
      (iv) Documents, as specified in Section 2, relating to beneficial owner, the managers, officers or employees, as the case may be, holding an attorney to transact on its behalf<br>
      (v) The names of all the partners and address of the registered office, and the principal place of its business, if it is different.<br>
      (vi) PAN or Form60 issued to the person holding POA on its behalf<br>
      (vii) Mode of operation in case of Partnership to be indicated clearly in AOF (Viz. All Partners jointly/severally (singly), Partner 1 &amp; 2 jointly/severally (singly) etc.)<br>
      (viii) A declaration containing the names of all the beneficial owners together with their shareholding/controlling interest/stake duly signed by the authorized signatory. (AnnexureIV)<br>
      (ix) Partnership letter dated…………………………and No……….. obtained and Signed by all partners.<br>
      &nbsp;&nbsp;&nbsp;(To be compulsorily obtained in case of partnership firms)<br>
      (x) Addresses of the Power of Attorney holders<br>
      (xi) Partnership letter obtained on PNB 38</td>
    </tr>
    <tr>
      <td>3</td><td><b>Limited Companies</b></td>
      <td>Certified copies of each of the following documents or the equivalent e-document thereof shall be obtained:<br>
      (i) Certificate of incorporation;<br>
      (ii) Memorandum and Articles of Association;<br>
      (iii) Permanent Account Number of the company;<br>
      (iv) A resolution from the Board of Directors and power of attorney granted to its managers, officers or employees to transact on its behalf;<br>
      (v) Documents, as specified in Section 2, relating to beneficial owner, the managers, officers or employees, as the case may be, holding an attorney to transact on the company's behalf.<br>
      (vi) the names of the relevant persons holding senior management position: and<br>
      (vii) the registered office and the principal place of its business, if it is different.<br>
      (viii) PAN or Form60 issued to the person holding POA to transact on company's behalf.<br>
      (ix) Certificate of commencement of business in case of Public limited company.<br>
      (x) CIN no.<br>
      (xi) Proof of current address.<br>
      (xii) Certificate of Registrar of Joint Stock Companies dated………………..<br>
      That the Company is entitled to commence business (for inspection, Entry in the Power of Attorney Register and return). A copy of the same is retained.<br>
      (This certificate is not required when,<br>
      &nbsp;&nbsp;a. The company is a private company, b. The company was registered before 1913 and does not invite the public to subscribe for shares.<br>
      &nbsp;&nbsp;c. The company is Limited by guarantee and does not have a Share capital).<br>

      <td>1</td><td><b>Proprietorship</b></td>
      <td>Any two of the following documents or the equivalent edocument thereof as a proof of business / activity in the name of the proprietary firm shall also be obtained:<br>
      (i) Registration certificate including Udyam Registration Certificate (URC) issued by the Government.<br>
      (ii) Certificate / Licence issued by the municipal authorities under Shop and Establishment Act.<br>
      (iii) Sales and income tax returns.<br>
      (iv) CST / VAT / GST certificate.<br>
      (v) Certificate / registration document issued by Sales Tax / Service Tax / Professional Tax authorities.<br>
      (vi) IEC (Importer Exporter Code) issued to the proprietary concern by the officeof DGFT / Licence / certificate of practice issued in the name of the proprietary concern by any professional body incorporated under a statute.<br>
      (vii) Complete Income Tax Return (not just the acknowledgement) in the name of the sole proprietor where the firm's income is reflected, duly authenticated / acknowledged by the Income Tax authorities.<br>

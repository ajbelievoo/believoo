  <div class="bar center mt4"><span>Current Account Rules</span></div>
  <div class="two-col" style="font-size:6.9px;line-height:1.35">
    <p><b>1.</b> Whenever the customer does not use alternate channels for opening the Current Account, payments to credit of an account with the Bank should ordinarily be accompanied by a pay-in slip duly signed by the constituent. Slips with counterfoils will be supplied in book form and the entry of the transactions made in the counterfoil will be authenticated by the initials of an authorised employee of the Bank. The depositor should satisfy himself that the transaction is so certified.</p>
    <p><b>2.</b> Cheques must be drawn on the Bank's printed forms. The Bank reserves its right to refuse payment of any cheque drawn otherwise. The bank reserves the right to refuse payment of cheques that have been altered in any way unless the alternation is authenticated by the drawer under full signature. Cheques should be drawn in such a way as to prevent alteration after issue, and the signature should be uniform with that on record at the Bank.</p>
    <p><b>3.</b> Constituents should not overdraw their accounts, even for small amounts without having made previous arrangements. Overdraft are granted on current accounts on terms as per extant instructions. Interest will be charged at the rates stipulated by the Bank and calculated upon the daily balances.</p>
    <p><b>4.</b> The Bank will register instructions from the drawer regarding cheques lost, stolen, etc. but cannot guarantee depositors against loss in such cases in the event of such a cheque being paid.</p>
    <p><b>5.</b> The bank collects bills, drafts, cheques, pay and pension bills, etc. on behalf of constituents. In personal accounts, the Bank offers up to a specified limit immediate credit in respect of cheques, drafts, dividend warrants, etc., payable at outstation branches.</p>
    <p><b>6.</b> Local cheques, etc. will be cleared under CTS Clearing</p>
    <p><b>7.</b> Cheques, bills, etc. sent in for collection and credit of an account must not be drawn against until they have been realised.</p>
    <p><b>8.</b> Bills, notes, etc. not payable on demand, intended for realisation by the Bank, should be sent at least one clear day before due date</p>
    <p><b>9.</b> The Bank accepts standing instructions on accounts for making periodic remittances, etc.</p>
    <p><b>10.</b> Statements of accounts will be sent to constituents periodically and can be obtained at any time on application. The entries of accounts should be carefully examined by the constituent, and, if any errors or omissions are discovered, the attention of the Bank must be drawn to them immediately. The Bank will not be responsible for any loss arising from neglect of this precaution.</p>
    <p><b>11.</b> Any change in the address of the constituent must be promptly advised to the Bank. In all their correspondence with the Bank and on pay-in slips etc. constituents should clearly mention the account number allotted at the time of opening of the account.</p>
    <p><b>12.</b> Accounts may be transferred at the request of the constituents to any other office of the Bank.</p>
    <p><b>13.</b> The Bank accepts securities and shares for safe custody and realisation of interest, dividends, etc. on terms which may be had on application.</p>
    <p><b>14.</b> The Bank reserves the right to alter/add to/delete any of these rules at any time.</p>

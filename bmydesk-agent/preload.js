const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('agent', {
    getScreenSources: () => ipcRenderer.invoke('get-screen-sources'),
    selectScreenSource: (id) => ipcRenderer.invoke('select-screen-source', id),
    getDisplaySize: () => ipcRenderer.invoke('get-display-size'),
    sendInput: (msg) => ipcRenderer.send('input-event', msg),
    openExternal: (url) => ipcRenderer.invoke('open-external', url),
    setViewMode: (on) => ipcRenderer.invoke('set-view-mode', on),
    loginItemGet: () => ipcRenderer.invoke('login-item-get'),
    loginItemSet: (on) => ipcRenderer.invoke('login-item-set', on),
    pickFile: () => ipcRenderer.invoke('pick-file'),
    saveFile: (name, b64) => ipcRenderer.invoke('save-file', name, b64),
    clipboardGet: () => ipcRenderer.invoke('clipboard-get'),
    clipboardSet: (t) => ipcRenderer.send('clipboard-set', t),
    sessionStatus: (active, label) => ipcRenderer.send('session-status', { active, label }),
    execCmd: (c) => ipcRenderer.invoke('exec-cmd', c),
    sysReboot: () => ipcRenderer.invoke('sys-reboot'),
    sysLock: () => ipcRenderer.invoke('sys-lock'),
    fsList: (p) => ipcRenderer.invoke('fs-list', p),
    fsGet: (p) => ipcRenderer.invoke('fs-get', p),
    laser: (on, x, y) => ipcRenderer.send('laser', on, x, y),
    watermark: (on, text) => ipcRenderer.send('watermark', on, text),
    privacyScreen: (on) => ipcRenderer.send('privacy-screen', !!on),
    attention: (name) => ipcRenderer.send('attention', name),
    onUpdate: (cb) => ipcRenderer.on('agent-update', (_e, d) => cb(d)),
    installUpdate: () => ipcRenderer.send('update-install'),
    onAuth: (cb) => ipcRenderer.on('agent-auth', (_e, d) => cb(d)),
    onConnect: (cb) => ipcRenderer.on('agent-connect', (_e, d) => cb(d)),
    onCsat: (cb) => ipcRenderer.on('csat-check', () => cb()),
    csatDone: () => ipcRenderer.send('csat-done'),
    platform: process.platform,
});
